// Exercises the interactive parts and reports console errors. Also loads the page over file://.
import { chromium } from "playwright";
import { serve } from "./serve.mjs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
const site = fileURLToPath(new URL("..", import.meta.url));
const server = await serve(4183, join(site, ".."));
const browser = await chromium.launch();
const errs = [];
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
page.on("console", (m) => { if (["error", "warning"].includes(m.type())) errs.push(m.text()); });
page.on("pageerror", (e) => errs.push(e.message));
await page.goto("http://127.0.0.1:4183/site/", { waitUntil: "networkidle" });
await page.waitForFunction(() => document.documentElement.dataset.ready === "1");
const r = {};
await page.click('#mxTable button[data-c="monad"][data-p="cold-warm-extcodesize"]');
r.inspector = (await page.textContent("#inspector")).replace(/\s+/g, " ").slice(0, 160);
await page.selectOption("#mxCat", "Precompiles");
r.rowsPrecompiles = await page.$$eval("#mxTable tbody tr:not(.cat)", (x) => x.length);
await page.check("#mxOnly");
r.onlyDiff = await page.textContent("#mxCount");
await page.selectOption("#mxCat", ""); await page.selectOption("#mxChain", "arbitrum-one");
r.chainFilter = await page.textContent("#mxCount");
await page.click('#chainPick button[data-chain="monad"]');
r.chainView = (await page.textContent("#chainView .cv-list")).replace(/\s+/g, " ").slice(0, 200);
await page.fill("#catQ", "prevrandao");
r.catalog = await page.textContent("#catCount");
await page.fill("#catQ", ""); await page.click("#catMore");
r.catalogAll = await page.$$eval("#catList details", (x) => x.length);
await page.click("#ck-0"); r.check = await page.textContent("#checkProgress");
await page.click("#step2"); await page.waitForTimeout(3500); r.exec = await page.textContent("#execTrace");
await page.click("#themeBtn"); r.theme = await page.evaluate(() => document.documentElement.dataset.theme);
await page.click('.cpill[data-chain="scroll"]'); r.pill = await page.$eval('#chainPick button[aria-pressed="true"]', (b) => b.dataset.chain);
// evidence link resolves
const href = await page.$eval("#inspector a.path, .ev a", (a) => a.href);
const rel = decodeURIComponent(href).split("github.com/DicksonWu654/evmish/blob/main/")[1];
r.evidence = href.slice(-60) + " -> " + (rel ? (await page.request.get("http://127.0.0.1:4183/" + rel)).status() : "no REPO_BASE prefix");
r.rpc = await page.$eval("#chainView dl", (d) => d.textContent.replace(/\s+/g, " ").slice(0, 160));
await page.click('#chainPick button[data-chain="ethereum"]'); r.ethRpc = (await page.textContent("#chainView dl")).replace(/\s+/g, " ").slice(0, 160);
r.rounds = (await page.textContent("#rounds tbody")).replace(/\s+/g, " ").slice(0, 200);
r.endpoints = await page.$$eval("#endpoints li", (x) => x.length + " | " + x.filter((l) => /third-party/.test(l.textContent)).map((l) => l.textContent).join("; "));
r.checklist = await page.$$eval("#checkGrid li", (x) => x.length + " | " + x[0].textContent.slice(0, 90));
r.initCode = await page.textContent("#machine .panel[data-p='0'] pre");
await page.click('#gasTable button[data-c="monad"][data-i="gas/memory-expand-32768-words/operation"]');
r.gasInsp = (await page.textContent("#gasInsp")).replace(/\s+/g, " ").slice(0, 200);
await page.click('#gasFam button[data-f="log"]'); r.gasLog = await page.textContent("#gasCount");
await page.uncheck("#gasOnly"); r.gasAll = await page.textContent("#gasCount");
await page.hover('#gasTable button[data-c="somnia"][data-i="gas/log4-256-bytes/operation"]'); r.gasTip = await page.textContent("#gasTip");
r.sweep = await page.$$eval("#sweepList > li", (x) => x.length + " | " + x.map((l) => l.querySelector("h3").textContent).join(" / ").slice(0, 400));
console.log(r);
// file:// load
const p2 = await browser.newPage();
p2.on("console", (m) => { if (["error", "warning"].includes(m.type())) errs.push("file: " + m.text()); });
p2.on("pageerror", (e) => errs.push("file: " + e.message));
await p2.goto("file://" + join(site, "index.html"));
await p2.waitForFunction(() => document.documentElement.dataset.ready, null, { timeout: 15000 });
console.log("file:// ready =", await p2.evaluate(() => document.documentElement.dataset.ready), await p2.textContent(".stat .v.hot"));
console.log(errs.length ? errs : "no console errors");
await browser.close(); server.close();
