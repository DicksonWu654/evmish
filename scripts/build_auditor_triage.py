#!/usr/bin/env python3
"""Build a chain-by-chain auditor triage map from the differential catalog."""

from __future__ import annotations

import json
import re
from collections import defaultdict
from pathlib import Path


ROOT = Path(__file__).resolve().parent.parent
CATALOG = ROOT / "CATALOG.md"
DATE = "2026-10-20"
MATRIX_DATE = "2026-10-18"
OUT_JSON = ROOT / "results" / DATE / "AUDITOR_TRIAGE.json"
OUT_MD = ROOT / "docs" / "auditor-triage.md"

ROW_RE = re.compile(
    r"^\| (\d+) \| (probe-verified|source-verified|doc-only) \| (.*?) \| (.*?) \| (.*?) \| (.*?) \| (.*?) \|$"
)
LINK_RE = re.compile(r"\[[^]]+\]\(([^)]+)\)")

FIXTURES = {
    "deployment": "examples/01_fork_gated_opcodes.sol",
    "addresses": "examples/06_create_addresses.sol",
    "precompiles": "examples/07_precompiles_and_system_addresses.sol",
    "accounts": "examples/08_account_code_and_aa.sol",
    "clocks": "examples/04_clock_hash_finality.sol",
    "fees": "examples/05_fee_and_gas.sol",
    "value": "examples/09_native_asset_and_fee_currency.sol",
    "authorization": "examples/03_cross_domain_sender.sol",
    "code-size": "examples/10_code_size_and_modularity.sol",
}

AREA_RULES = (
    ("authorization", ("alias", "sender", "onlyowner", "tx.origin")),
    ("addresses", ("create2", "create address", "deployer formula")),
    ("code-size", ("code-size", "code size", "runtime code", "init code")),
    ("deployment", ("opcode", "push0", "tstore", "tload", "mcopy", "blobhash", "blobbasefee", "fork")),
    ("accounts", ("extcode", "7702", "delegated", "eoa", "system candidate")),
    ("precompiles", ("precompile", "address 0x", "kzg", "p256", "ecrecover", "blake2")),
    ("fees", ("fee", "gas", "reserve balance", "gaslimit", "gas limit")),
    ("clocks", ("number", "timestamp", "blockhash", "prevrandao", "coinbase", "finality", "sequencer")),
    ("value", ("native", "rebas", "stablecoin", "value movement", "asset")),
)

AREA_PRIORITY = {
    "authorization": 5,
    "accounts": 5,
    "deployment": 4,
    "addresses": 4,
    "code-size": 4,
    "precompiles": 4,
    "fees": 4,
    "clocks": 3,
    "value": 3,
}

ACTION = {
    "authorization": "Trace the authenticated cross-domain sender and test the owner check with the messenger's aliasing rule.",
    "accounts": "Remove EOA-by-code assumptions; test an EOA, smart account, delegated account, and system address.",
    "deployment": "Compile for the target fork and run the opcode probe before accepting deployment bytecode.",
    "addresses": "Compare the target's CREATE/CREATE2 result with the off-chain formula before funding a predicted address.",
    "code-size": "Test the target's init and runtime boundaries with a target-chain deployment gate.",
    "precompiles": "Run the known-answer vector at the target address and treat empty success as a distinct result.",
    "fees": "Price the operation with the target fee oracle and charging rule; do not infer cost from Ethereum gas alone.",
    "clocks": "Use the target header and finality policy for timelocks, epochs, and randomness inputs.",
    "value": "Test native value, fee currency, balance, and refund paths with the target asset model.",
}


def parse_rows() -> list[dict]:
    rows = []
    for line in CATALOG.read_text(encoding="utf-8").splitlines():
        match = ROW_RE.match(line)
        if not match:
            continue
        number, label, chain, divergence, consequence, evidence, date = match.groups()
        rows.append(
            {
                "catalog_row": int(number),
                "evidence_label": label,
                "chain": chain,
                "divergence": divergence,
                "security_consequence": consequence,
                "evidence": evidence,
                "evidence_links": LINK_RE.findall(evidence),
                "date": date,
            }
        )
    if not rows:
        raise SystemExit("no catalog rows found")
    return rows


def area_for(row: dict) -> str:
    text = (row["divergence"] + " " + row["security_consequence"]).lower()
    for area, needles in AREA_RULES:
        if any(needle in text for needle in needles):
            return area
    return "value"


def make_finding(row: dict) -> dict:
    area = area_for(row)
    return {
        **row,
        "risk_area": area,
        "priority": AREA_PRIORITY[area],
        "fixture": FIXTURES[area],
        "review_action": ACTION[area],
    }


def markdown(data: dict, by_chain: dict[str, list[dict]]) -> str:
    lines = [
        "# Auditor triage map",
        "",
        "<!-- GENERATED BY scripts/build_auditor_triage.py FROM CATALOG.md -->",
        "",
        f"This map turns the {data['catalog_rows']} dated differential catalog rows into a review order. It keeps source-verified claims visible, but every probe finding remains tied to its primary and later-block evidence. Priority is a review hint: authorization and account-model assumptions come first, then deployment, address, precompile, and fee boundaries, followed by clocks and value models.",
        "",
        "Each row names a minimal Solidity fixture and a concrete question for an auditor. Start with the target chain's section, then open the linked catalog evidence before accepting a compatibility claim.",
        "",
        "## Chain triage",
        "",
    ]
    for chain in sorted(by_chain):
        findings = by_chain[chain]
        lines.extend([f"### {chain}", "", "| Priority | Catalog row | Risk area | What to check | Fixture | Evidence |", "|---:|---:|---|---|---|---|"])
        for finding in sorted(findings, key=lambda item: (-item["priority"], item["catalog_row"]))[:5]:
            evidence = "; ".join(f"[{Path(link).name if not link.startswith(('http://', 'https://')) else 'source'}]({link})" for link in finding["evidence_links"])
            lines.append(
                f"| {finding['priority']} | {finding['catalog_row']} | {finding['risk_area']} | {finding['review_action']} | [{Path(finding['fixture']).name}]({finding['fixture']}) | {evidence} |"
            )
        lines.extend(["", f"All {len(findings)} catalog findings for this scope are in `results/{DATE}/AUDITOR_TRIAGE.json`.", ""])
    lines.extend(
        [
            "## Evidence gate",
            "",
            "A probe row is actionable only when its catalog entry links both the primary result and a later-block confirmation. A source row is a documented assumption to validate on the target chain; it is not a live VM observation. RPC rejection and unavailable cells remain in the differential matrix and are not promoted by this map.",
            "",
            f"Generated from [CATALOG.md](../CATALOG.md), [DIFFERENTIAL_MATRIX.md](../results/{MATRIX_DATE}/DIFFERENTIAL_MATRIX.md), and the three {DATE} expansion matrices.",
            "",
        ]
    )
    return "\n".join(lines)


def main() -> None:
    rows = parse_rows()
    findings = [make_finding(row) for row in rows]
    by_chain: dict[str, list[dict]] = defaultdict(list)
    for finding in findings:
        by_chain[finding["chain"]].append(finding)
    data = {
        "generated_by": "scripts/build_auditor_triage.py",
        "date": DATE,
        "catalog": "CATALOG.md",
        "matrix": f"results/{MATRIX_DATE}/DIFFERENTIAL_MATRIX.md",
        "catalog_rows": len(findings),
        "chains": sorted(by_chain),
        "findings": findings,
    }
    OUT_JSON.write_text(json.dumps(data, indent=2) + "\n", encoding="utf-8")
    OUT_MD.write_text(markdown(data, by_chain), encoding="utf-8")
    print(f"wrote auditor triage for {len(findings)} catalog rows across {len(by_chain)} scopes")


if __name__ == "__main__":
    main()
