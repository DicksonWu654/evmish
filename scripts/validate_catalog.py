#!/usr/bin/env python3
"""Validate catalog row structure and every local evidence path."""

from __future__ import annotations

import json
import re
from pathlib import Path


ROOT = Path(__file__).resolve().parent.parent
CATALOG = ROOT / "CATALOG.md"
DATE = "2026-10-18"
MATRIX = ROOT / "results" / DATE / "DIFFERENTIAL_MATRIX.md"
ROW_RE = re.compile(r"^\| (\d+) \| (.*?) \| (.*?) \| (.*?) \| (.*?) \| (.*?) \| (.*?) \|$")
ALLOWED_LABELS = {"probe-verified", "source-verified", "doc-only"}
MATRIX_CELLS = {"same", "diff", "unsupported", "rejected", "unavailable", "state-only", "unstable-endpoint", "rpc-simulation", "unverifiable"}


def main() -> int:
    rows = []
    for line in CATALOG.read_text(encoding="utf-8").splitlines():
        match = ROW_RE.match(line)
        if match:
            rows.append(match.groups())
    if not rows:
        raise SystemExit("no catalog rows found")

    numbers = [int(row[0]) for row in rows]
    if numbers != list(range(1, len(rows) + 1)):
        raise SystemExit(f"catalog row numbers are not contiguous: {numbers[:5]}...{numbers[-5:]}")
    counts = {label: 0 for label in ALLOWED_LABELS}
    local_evidence = 0
    for number, label, chain, divergence, consequence, evidence, date in rows:
        if label not in ALLOWED_LABELS:
            raise SystemExit(f"row {number}: invalid evidence label {label!r}")
        if date not in {"2026-10-18", "2026-10-20"}:
            raise SystemExit(f"row {number}: unexpected observation date {date!r}")
        counts[label] += 1
        targets = re.findall(r"\]\(([^)]+)\)", evidence)
        if not targets:
            raise SystemExit(f"row {number}: evidence has no link")
        if label == "probe-verified" and not any(target.startswith("results/") for target in targets):
            raise SystemExit(f"row {number}: probe row has no local result evidence")
        if label == "probe-verified":
            result_targets = [target for target in targets if target.startswith("results/")]
            confirmation_marker = "differential-confirmation/" if date == "2026-10-18" else "/confirm/"
            if len(result_targets) < 2 or not any(confirmation_marker in target for target in result_targets):
                raise SystemExit(f"row {number}: probe divergence lacks later-block confirmation evidence")
            if any(marker in divergence.lower() for marker in ("profile completed", "ethereum mainnet")):
                raise SystemExit(f"row {number}: padded baseline/profile row remains in differential catalog")
        if label == "source-verified" and not any(target.startswith(("http://", "https://")) for target in targets):
            raise SystemExit(f"row {number}: source row has no pinned URL")
        for target in targets:
            if target.startswith(("http://", "https://", "#")):
                continue
            local = target.split("#", 1)[0]
            path = ROOT / local
            if not path.exists():
                raise SystemExit(f"row {number}: missing evidence path {target}")
            local_evidence += 1
            if path.suffix == ".json":
                try:
                    json.loads(path.read_text(encoding="utf-8"))
                except json.JSONDecodeError as exc:
                    raise SystemExit(f"row {number}: invalid JSON evidence {target}: {exc}") from exc

    catalog_text = CATALOG.read_text(encoding="utf-8")
    if not catalog_text.startswith("# Differential EVM divergence catalog\n"):
        raise SystemExit("catalog is not the differential catalog")
    if not MATRIX.exists() or "GENERATED BY scripts/build_catalog.py" not in MATRIX.read_text(encoding="utf-8"):
        raise SystemExit("differential matrix is missing or not generated by build_catalog.py")
    matrix_lines = MATRIX.read_text(encoding="utf-8").splitlines()
    summary = json.loads((ROOT / "results" / DATE / "SUMMARY.json").read_text(encoding="utf-8"))
    expected_chains = [row["chain"] for row in sorted(summary["chains"], key=lambda row: row["chain"])]
    matrix_header = next((line for line in matrix_lines if line.startswith("| Probe |")), "")
    if matrix_header != "| Probe | " + " | ".join(expected_chains) + " |":
        raise SystemExit("differential matrix chain columns do not match SUMMARY.json")
    matrix_rows = [line for line in matrix_lines if line.startswith("| `")]
    if len(matrix_rows) != len(summary["probe_names"]):
        raise SystemExit("differential matrix probe rows do not match SUMMARY.json")
    for line in matrix_rows:
        cells = [cell.strip() for cell in line.strip("|").split("|")][1:]
        if any(cell not in MATRIX_CELLS for cell in cells):
            raise SystemExit(f"differential matrix contains an invalid cell: {line}")

    if any("extcode-delegated-7702" in row[3] for row in rows):
        raise SystemExit("fixed-address EIP-7702 comparison remains a catalog divergence")
    if "Plasma stablecoin fee model" in catalog_text:
        raise SystemExit("unverifiable Plasma fee row remains in the catalog")
    matrix_text = MATRIX.read_text(encoding="utf-8")
    if "state-only" not in matrix_text or "unstable-endpoint" not in matrix_text or "rpc-simulation" not in matrix_text:
        raise SystemExit("matrix does not retain state-only, unstable-endpoint, and rpc-simulation audit markers")
    quality_path = ROOT / "results" / DATE / "ENDPOINT_QUALITY.json"
    quality = json.loads(quality_path.read_text(encoding="utf-8"))
    hyperevm_quality = quality.get("chains", {}).get("hyperevm", {})
    for chain in ("cronos", "hyperevm"):
        entry = quality.get("chains", {}).get(chain, {})
        required = {"number", "timestamp", "basefee", "prevrandao"} | ({"gaslimit"} if chain == "hyperevm" else set())
        if entry.get("status") != "unstable" or not set(entry.get("probes", [])) >= required:
            raise SystemExit(f"{chain} endpoint-quality record does not cover affected block-context probes")
    corrections = (ROOT / "docs" / "catalog-correction-r1.md").exists() and (ROOT / "docs" / "catalog-correction-r2.md").exists()
    public_summary = (ROOT / "docs" / "verification.md").exists()
    if not (corrections or public_summary):
        raise SystemExit("catalog correction record is missing")
    simulation = ROOT / "results" / DATE / "RPC_SIMULATION.json"
    if not simulation.exists() or json.loads(simulation.read_text(encoding="utf-8")).get("classification") != "rpc-simulation":
        raise SystemExit("BASEFEE RPC simulation record is missing")

    heading = catalog_text.splitlines()[6]
    expected_heading = f"Catalog coverage: **{len(rows)} rows** ({counts['probe-verified']} probe-verified, {counts['source-verified']} source-verified, {counts['doc-only']} doc-only)."
    if not heading.startswith(expected_heading):
        raise SystemExit(f"catalog heading does not match rows: {heading}")
    print(f"catalog validation passed: {len(rows)} rows, {counts['probe-verified']} probe, {counts['source-verified']} source, {local_evidence} local evidence links")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
