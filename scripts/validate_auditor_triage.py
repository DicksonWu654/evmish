#!/usr/bin/env python3
"""Validate the generated auditor triage map covers the full catalog."""

from __future__ import annotations

import json
import re
from pathlib import Path


ROOT = Path(__file__).resolve().parent.parent
DATE = "2026-10-20"
CATALOG = ROOT / "CATALOG.md"
TRIAGE = ROOT / "results" / DATE / "AUDITOR_TRIAGE.json"
DOC = ROOT / "docs" / "auditor-triage.md"
ROW_RE = re.compile(r"^\| (\d+) \| (probe-verified|source-verified|doc-only) \| (.*?) \| (.*?) \| (.*?) \| (.*?) \| (.*?) \|$")


def main() -> int:
    catalog_rows = []
    for line in CATALOG.read_text(encoding="utf-8").splitlines():
        match = ROW_RE.match(line)
        if match:
            catalog_rows.append(int(match.group(1)))
    if not catalog_rows or catalog_rows != list(range(1, len(catalog_rows) + 1)):
        raise SystemExit("catalog rows are missing or non-contiguous")
    data = json.loads(TRIAGE.read_text(encoding="utf-8"))
    if data.get("generated_by") != "scripts/build_auditor_triage.py":
        raise SystemExit("triage JSON is not generated by the required script")
    if data.get("catalog_rows") != len(catalog_rows):
        raise SystemExit("triage/catalog row counts differ")
    findings = data.get("findings", [])
    ids = [item.get("catalog_row") for item in findings]
    if sorted(ids) != catalog_rows:
        raise SystemExit("triage does not cover each catalog row exactly once")
    required = {"evidence_label", "chain", "divergence", "security_consequence", "evidence_links", "risk_area", "priority", "fixture", "review_action"}
    for item in findings:
        if not required.issubset(item):
            raise SystemExit(f"row {item.get('catalog_row')}: missing triage field")
        fixture = ROOT / item["fixture"]
        if not fixture.exists():
            raise SystemExit(f"row {item['catalog_row']}: missing fixture {item['fixture']}")
        if not item["evidence_links"]:
            raise SystemExit(f"row {item['catalog_row']}: no evidence links")
        for link in item["evidence_links"]:
            if link.startswith(("http://", "https://")):
                continue
            if not (ROOT / link.split("#", 1)[0]).exists():
                raise SystemExit(f"row {item['catalog_row']}: missing evidence path {link}")
    if not DOC.exists() or "GENERATED BY scripts/build_auditor_triage.py" not in DOC.read_text(encoding="utf-8"):
        raise SystemExit("auditor triage markdown is missing its generated marker")
    for chain in data["chains"]:
        if f"### {chain}" not in DOC.read_text(encoding="utf-8"):
            raise SystemExit(f"markdown is missing chain section {chain}")
    print(f"auditor triage validation passed: {len(findings)} rows across {len(data['chains'])} scopes")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
