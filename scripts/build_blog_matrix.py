#!/usr/bin/env python3
"""Build the blog's chain matrix table and SVG from dated probe results."""

from __future__ import annotations

import html
import json
from pathlib import Path


ROOT = Path(__file__).resolve().parent.parent
RESULTS = ROOT / "results" / "2026-10-18"
BLOG = ROOT / "blog"
DRAFT = BLOG / "draft.md"
ENDPOINT_QUALITY = RESULTS / "ENDPOINT_QUALITY.json"


def unstable_number_chain(chain: str) -> bool:
    quality = json.loads(ENDPOINT_QUALITY.read_text(encoding="utf-8"))
    entry = quality.get("chains", {}).get(chain, {})
    return entry.get("probe") == "number" and entry.get("status") == "unstable"


def interpretation(result: dict, probe: str) -> dict:
    return result.get("probes", {}).get(probe, {}).get("interpretation", {})


def matrix_rows() -> list[dict]:
    rows = []
    for path in sorted(RESULTS.glob("*/*.json")):
        result = json.loads(path.read_text(encoding="utf-8"))
        chain = result.get("chain")
        if not chain:
            continue
        blob = interpretation(result, "blobbasefee")
        number = interpretation(result, "number")
        ripemd = interpretation(result, "precompile-0x03-ripemd160")
        cold = interpretation(result, "cold-warm-extcodesize")
        rows.append(
            {
                "chain": chain,
                "chain_id": result.get("chain_id_expected", "—"),
                "status": result.get("status", "—"),
                "block": result.get("block_number") or "—",
                "blobbasefee": blob.get("status", "—"),
                "number": (
                    "unstable-endpoint"
                    if unstable_number_chain(chain)
                    else
                    "match"
                    if number.get("header_matches") is True
                    else "diff"
                    if number.get("header_matches") is False
                    else number.get("status", "—")
                ),
                "ripemd160": (
                    str(ripemd["precompile_call_status"])
                    if "precompile_call_status" in ripemd
                    else "—"
                ),
                "cold_delta": cold.get("gas_delta", "—"),
                "evidence": f"results/2026-10-18/{chain}/{chain}.json",
            }
        )
    baseline = next(row for row in rows if row["chain"] == "ethereum")
    compared = ("status", "blobbasefee", "number", "ripemd160", "cold_delta")
    return [
        row
        for row in rows
        if row["status"] != "unavailable"
        and any(
            row[key] != baseline[key]
            for key in compared
            if not (key == "number" and unstable_number_chain(row["chain"]))
        )
    ]


def md_table(rows: list[dict]) -> str:
    lines = [
        "| Chain | ID | Profile | Block | BLOBBASEFEE | NUMBER/header | RIPEMD160 call | Cold access delta | Evidence |",
        "| --- | ---: | --- | --- | --- | --- | ---: | ---: | --- |",
    ]
    for row in rows:
        evidence_link = f"../{row['evidence']}"
        lines.append(
            "| {chain} | {chain_id} | {status} | {block} | {blobbasefee} | {number} | {ripemd160} | {cold_delta} | [{evidence}]({evidence_link}) |".format(
                evidence_link=evidence_link,
                **row,
            )
        )
    return "\n".join(lines)


def svg(rows: list[dict]) -> str:
    columns = [
        ("Chain", 165),
        ("ID", 82),
        ("Profile", 90),
        ("Block", 120),
        ("BLOBBASEFEE", 120),
        ("NUMBER/header", 115),
        ("RIPEMD160", 95),
        ("Cold delta", 105),
    ]
    row_height = 27
    header_height = 42
    width = sum(width for _, width in columns)
    height = header_height + row_height * len(rows) + 18
    parts = [
        '<?xml version="1.0" encoding="UTF-8"?>',
        '<!-- Generated by scripts/build_blog_matrix.py from results/2026-10-18/*/*.json. -->',
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 {width} {height}">',
        '<style>text{font-family:ui-monospace,SFMono-Regular,Menlo,monospace;font-size:12px;fill:#18212b}.head{font-weight:700;fill:#fff}.grid{stroke:#ccd5df;stroke-width:1}.ok{fill:#e8f5e9}.warn{fill:#fff4d6}.bad{fill:#fde8e7}.muted{fill:#f2f4f7}</style>',
        f'<rect width="{width}" height="{height}" fill="#fff"/>',
        f'<rect width="{width}" height="{header_height}" fill="#243b53"/>',
    ]
    x = 0
    for title, col_width in columns:
        parts.append(f'<text class="head" x="{x + 8}" y="26">{html.escape(title)}</text>')
        x += col_width
    parts.append(f'<line class="grid" x1="0" y1="{header_height}" x2="{width}" y2="{header_height}"/>')

    def cell_class(value: str) -> str:
        if value in {"ok", "match", "1"}:
            return "ok"
        if value in {"rpc-rejected", "execution-failure", "diff", "degraded", "partial"}:
            return "bad"
        if value in {"—", "unavailable"}:
            return "muted"
        return "warn"

    for index, row in enumerate(rows):
        y = header_height + index * row_height
        values = [
            row["chain"],
            str(row["chain_id"]),
            row["status"],
            row["block"],
            row["blobbasefee"],
            row["number"],
            row["ripemd160"],
            str(row["cold_delta"]),
        ]
        x = 0
        for value, (_, col_width) in zip(values, columns):
            parts.append(
                f'<rect class="{cell_class(value)}" x="{x}" y="{y}" width="{col_width}" height="{row_height}"/>'
            )
            parts.append(f'<text x="{x + 8}" y="{y + 18}">{html.escape(value)}</text>')
            parts.append(f'<line class="grid" x1="{x}" y1="{y}" x2="{x}" y2="{y + row_height}"/>')
            x += col_width
        parts.append(f'<line class="grid" x1="0" y1="{y + row_height}" x2="{width}" y2="{y + row_height}"/>')
    parts.append("</svg>")
    return "\n".join(parts) + "\n"


def main() -> int:
    rows = matrix_rows()
    if not 1 <= len(rows) < 27:
        raise SystemExit(f"expected a non-empty differing subset of 27 registry rows, found {len(rows)}")
    BLOG.mkdir(parents=True, exist_ok=True)
    table = md_table(rows)
    (BLOG / "chain-matrix.md").write_text(
        "# Differential chain probe matrix\n\nCaptured 2026-10-18 from the committed raw results. This figure includes only chains that differ from Ethereum in at least one displayed security-relevant dimension. `RIPEMD160 call` is the inner precompile call status; `—` means the endpoint was unavailable or the probe did not run.\n\n"
        + table
        + "\n",
        encoding="utf-8",
    )
    (BLOG / "chain-matrix.svg").write_text(svg(rows), encoding="utf-8")
    if DRAFT.exists():
        draft = DRAFT.read_text(encoding="utf-8")
        start = "<!-- GENERATED-MATRIX-TABLE -->"
        end = "<!-- END-GENERATED-MATRIX-TABLE -->"
        if start in draft and end in draft:
            before, remainder = draft.split(start, 1)
            _, after = remainder.split(end, 1)
            DRAFT.write_text(before + start + "\n" + table + "\n" + end + after, encoding="utf-8")
    print(f"wrote {len(rows)} differing rows to blog/chain-matrix.md and blog/chain-matrix.svg")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
